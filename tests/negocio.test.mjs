import { beforeEach, test } from 'node:test'
import assert from 'node:assert/strict'

const memoria = new Map()
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: k => memoria.get(k) || null, setItem: (k, v) => memoria.set(k, v), removeItem: k => memoria.delete(k) }, configurable: true })
const { almacen } = await import('../src/domain/almacen.js')
const { controles, ControlRegistro, ControlCancelacion, ControlCheckIn } = await import('../src/domain/controles.js')
const { RepositorioReservas } = await import('../src/domain/repositorios.js')
const { ServidorCorreo } = await import('../src/domain/servicios.js')
const { sumarDias } = await import('../src/domain/datos.js')

const tarjeta = { titular: 'Persona de Prueba', numero: '4242424242424242', vencimiento: '12/99', cvv: '123' }
const entrar = (cuenta = 'cliente') => controles.login.procesarLogin(`${cuenta}@logica404.com`, 'Demo404!')
function solicitud(asiento = '1A') {
  const vuelo = almacen.obtener().vuelos.find(v => v.origen === 'SDQ' && v.destino === 'SJU' && v.horaPartida.startsWith(sumarDias(1, almacen.ahora())))
  return { vueloId: vuelo.idVuelo, pasajeros: [{ nombre: 'Prueba', apellido: 'Reyes', documento: 'RD1234567', asiento }], servicios: ['equipaje'], usarMillas: false, clase: 'economica' }
}
beforeEach(() => { almacen.reiniciar() })

test('un visitante puede consultar vuelos pero no reservar', () => {
  const s = solicitud()
  assert.ok(controles.consulta.procesarBusqueda({ origen: 'SDQ', destino: 'SJU', fecha: sumarDias(1), pasajeros: '1' }).length >= 3)
  assert.throws(() => controles.reserva.confirmarReserva(tarjeta, s), /Inicia sesión/)
})
test('registro valida los datos, la contraseña y el correo duplicado', () => {
  const control = new ControlRegistro()
  const cuenta = { nombre: 'Ana', apellido: 'Pérez', direccion: 'Santo Domingo', telefono: '8095551234', correo: 'ana@prueba.test', contrasena: 'Prueba404!' }
  assert.throws(() => control.procesarRegistro({ ...cuenta, contrasena: 'abc' }, 'minorista'), /contraseña/)
  assert.throws(() => control.procesarRegistro(cuenta, 'corporativo'), /compañía/)
  const u = control.procesarRegistro(cuenta, 'minorista')
  assert.ok(u.idUsuario)
  assert.throws(() => control.procesarRegistro(cuenta, 'minorista'), /ya está registrado/)
  assert.equal(controles.login.procesarLogin(cuenta.correo, cuenta.contrasena), true)
})
test('login rechaza campos vacíos, usuarios inexistentes y contraseña incorrecta', () => {
  assert.throws(() => controles.login.procesarLogin('', ''), /Completa/)
  assert.throws(() => controles.login.procesarLogin('nadie@prueba.test', 'incorrecta'), /no está registrado/)
  assert.throws(() => controles.login.procesarLogin('cliente@logica404.com', 'incorrecta'), /incorrectas/)
  assert.equal(almacen.obtener().sesion, null)
})
test('la búsqueda respeta destino, fecha y hora exacta y contempla cero coincidencias', () => {
  const criterios = { origen: 'SDQ', destino: 'SJU', fecha: sumarDias(1), pasajeros: '1', horaPartida: '13:45' }
  const vuelos = controles.consulta.procesarBusqueda(criterios)
  assert.equal(vuelos.length, 1)
  assert.equal(vuelos[0].horaPartida.slice(11, 16), '13:45')
  assert.equal(controles.consulta.procesarBusqueda({ ...criterios, horaPartida: '02:00' }).length, 0)
  assert.throws(() => controles.consulta.procesarBusqueda({ ...criterios, destino: 'SDQ' }), /diferentes/)
})
test('un pago rechazado no crea reserva, ocupa asiento ni modifica millas', () => {
  entrar('empresa')
  const previo = JSON.stringify(almacen.obtener())
  assert.throws(() => controles.reserva.confirmarReserva({ ...tarjeta, numero: '4000000000000002' }, solicitud()), /Pago rechazado/)
  assert.equal(JSON.stringify(almacen.obtener()), previo)
})
test('reservar ocupa el asiento, calcula los extras y genera un comprobante simulado sin guardar tarjeta', () => {
  entrar()
  const s = solicitud()
  const v = almacen.obtener().vuelos.find(v => v.idVuelo === s.vueloId)
  const r = controles.reserva.confirmarReserva(tarjeta, s)
  assert.equal(r.montoTotal, v.tarifa + 24 + 35)
  assert.match(r.codigoPNR, /^[A-Z2-9]{6}$/)
  assert.ok(almacen.obtener().vuelos.find(v => v.idVuelo === s.vueloId).asientosOcupados.includes('1A'))
  assert.ok(almacen.obtener().mensajes.some(m => m.asunto.includes(r.codigoPNR)))
  assert.equal(JSON.stringify(almacen.obtener()).includes(tarjeta.numero), false)
  assert.throws(() => controles.reserva.confirmarReserva(tarjeta, s), /asiento disponible/)
})
test('los asientos deben ser distintos por pasajero y el grupo se confirma completo', () => {
  entrar()
  const s = solicitud()
  s.pasajeros.push({ nombre: 'Otra', apellido: 'Reyes', documento: 'RD7654321', asiento: '1A' })
  assert.throws(() => controles.reserva.confirmarReserva(tarjeta, s), /diferente/)
  s.pasajeros[1].asiento = '1C'
  const r = controles.reserva.confirmarReserva(tarjeta, s)
  assert.deepEqual(r.asientos, ['1A', '1C'])
  assert.equal(r.montoTotal, (129 + 24 + 35) * 2)
})
test('las millas corporativas se descuentan, acumulan y revierten al cancelar', () => {
  entrar('empresa')
  const s = { ...solicitud(), usarMillas: true }
  const r = controles.reserva.confirmarReserva(tarjeta, s)
  const u = () => almacen.obtener().usuarios.find(u => u.idUsuario === 'corporativo-demo')
  assert.equal(r.millasDescontadas, 3000)
  assert.equal(r.montoTotal, 129 + 24 + 35 - 30)
  assert.equal(u().millas, 12500 - 3000 + 250)
  controles.cancelacion.CancelarReservacion(r.codigoPNR, 'Cambio de planes')
  assert.equal(u().millas, 12500)
})
test('cancelar devuelve 80 %, libera asientos y rechaza la cancelación duplicada', () => {
  entrar()
  const s = solicitud()
  const r = controles.reserva.confirmarReserva(tarjeta, s)
  const monto = controles.cancelacion.CancelarReservacion(r.codigoPNR, 'Cambio de planes')
  assert.equal(monto, Math.round(r.montoTotal * 80) / 100)
  assert.equal(new RepositorioReservas().buscarReservacion(r.codigoPNR).estadoReserva, 'CANCELADA')
  assert.equal(almacen.obtener().vuelos.find(v => v.idVuelo === s.vueloId).asientosOcupados.includes('1A'), false)
  assert.throws(() => controles.cancelacion.CancelarReservacion(r.codigoPNR, 'De nuevo'), /ya está cancelada/)
})
test('cancelación fuera de siete días o devolución rechazada conserva la reserva', () => {
  entrar()
  assert.throws(() => controles.cancelacion.CancelarReservacion('ANT404', 'Cambio'), /siete días/)
  almacen.actualizar(s => { s.configuracion.pago = 'rechazado' })
  assert.throws(() => controles.cancelacion.CancelarReservacion('L404DE', 'Cambio'), /devolución/)
  assert.equal(new RepositorioReservas().buscarReservacion('L404DE').estadoReserva, 'CONFIRMADA')
})
test('check-in valida propietario, apellido, ventana y genera un pase reutilizable', () => {
  entrar()
  const r = new RepositorioReservas().buscarReservacion('L404DE')
  almacen.actualizar(s => { s.configuracion.ahora = new Date(new Date(r.fechaHoraAbordaje).getTime() - 3 * 3600000).toISOString() })
  assert.throws(() => controles.checkin.procesarCheckIn('L404DE', 'Incorrecto'), /No encontramos/)
  const pase = controles.checkin.procesarCheckIn('L404DE', 'Reyes')
  assert.equal(pase.asiento, '5A')
  assert.equal(pase.codigoReservacion, 'L404DE')
  assert.equal(controles.checkin.procesarCheckIn('L404DE', 'Reyes').codigoPase, pase.codigoPase)
  entrar('empresa')
  assert.throws(() => controles.checkin.procesarCheckIn('L404DE', 'Reyes'), /No encontramos/)
})
test('migración rechazada o no disponible y check-in fuera de ventana no generan pases', () => {
  entrar()
  almacen.actualizar(s => { s.configuracion.migracion = 'rechazada' })
  assert.throws(() => controles.checkin.procesarCheckIn('L404DE', 'Reyes'), /no aprobó/)
  almacen.actualizar(s => { s.configuracion.migracion = 'no-disponible' })
  assert.throws(() => controles.checkin.procesarCheckIn('L404DE', 'Reyes'), /no está disponible/)
  almacen.actualizar(s => { s.configuracion.migracion = 'aprobada'; s.configuracion.ahora = new Date(Date.now() - 8 * 3600000).toISOString() })
  assert.throws(() => controles.checkin.procesarCheckIn('L404DE', 'Reyes'), /entre 2 y 5/)
  assert.equal(new RepositorioReservas().buscarReservacion('L404DE').paseAbordar, undefined)
})
test('actualización requiere agente, notifica al cliente y mantiene el precio contratado', () => {
  entrar()
  const r = new RepositorioReservas().buscarReservacion('L404DE')
  const v = almacen.obtener().vuelos.find(v => v.idVuelo === r.vueloId)
  const actualizacion = { tarifa: 250, puerta: 'C3', estado: 'Retrasado', horaPartida: new Date(new Date(v.horaPartida).getTime() + 3600000).toISOString() }
  assert.throws(() => controles.actualizacion.GuardarCambios(v.idVuelo, actualizacion), /autorización/)
  controles.checkin.procesarCheckIn('L404DE', 'Reyes')
  entrar('agente')
  assert.equal(controles.actualizacion.GuardarCambios(v.idVuelo, actualizacion), 1)
  const reserva = almacen.obtener().reservas.find(res => res.codigoPNR === 'L404DE')
  assert.equal(reserva.estadoCheckIn, 'PENDIENTE')
  assert.equal(reserva.paseAbordar, null)
  assert.equal(reserva.montoTotal, 149)
  assert.ok(almacen.obtener().mensajes.some(m => m.asunto.includes('Actualización')))
})
test('los correos quedan pendientes cuando falla el servicio y se pueden reintentar', () => {
  entrar()
  almacen.actualizar(s => { s.configuracion.correo = 'no-disponible' })
  const r = controles.reserva.confirmarReserva(tarjeta, solicitud())
  assert.equal(almacen.obtener().mensajes.find(m => m.asunto.includes(r.codigoPNR)).estado, 'Pendiente')
  assert.throws(() => new ServidorCorreo().reintentarPendientes(), /sigue sin/)
  almacen.actualizar(s => { s.configuracion.correo = 'disponible' })
  new ServidorCorreo().reintentarPendientes()
  assert.equal(almacen.obtener().mensajes.filter(m => m.estado === 'Pendiente').length, 0)
})
test('los límites inclusivos de siete días y de 2 a 5 horas son exactos', () => {
  const control = new ControlCancelacion()
  const ahora = almacen.ahora().getTime()
  const r = { fechaReserva: new Date(ahora - 7 * 86400000).toISOString(), fechaHoraAbordaje: new Date(ahora + 24 * 3600000).toISOString() }
  almacen.actualizar(s => { s.configuracion.ahora = new Date(ahora).toISOString() })
  assert.equal(control.VerificarFechaYPlazo(r), true)
  almacen.actualizar(s => { s.configuracion.ahora = new Date(ahora + 1).toISOString() })
  assert.equal(control.VerificarFechaYPlazo(r), false)
  almacen.actualizar(s => { s.configuracion.ahora = new Date(ahora).toISOString() })
  const checkin = new ControlCheckIn()
  for (const [horas, esperado] of [[2, true], [5, true], [1.99, false], [5.01, false]]) assert.equal(checkin.verificarPlazo({ fechaHoraAbordaje: new Date(ahora + horas * 3600000).toISOString() }), esperado)
})
